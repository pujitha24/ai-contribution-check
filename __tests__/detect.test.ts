import { describe, expect, it } from 'vitest'
import { detectAiAssistance, detectInCommit, detectInDescription } from '../src/detect.js'
import { DEFAULT_BOT_AUTHORS } from '../src/identities.js'
import { commit } from './helpers.js'

function polarity(body: string): string[] {
  return detectInDescription(body).map((s) => `${s.kind}:${s.polarity}`)
}

describe('description: positive disclosures', () => {
  const cases: [string, string, string?][] = [
    ['This PR was written with the help of Claude Code.', 'description-statement', 'Claude'],
    ['I used GitHub Copilot to generate the unit tests.', 'description-statement', 'GitHub Copilot'],
    ['🤖 Generated with [Claude Code](https://claude.com/claude-code)', 'description-statement', 'Claude'],
    ['Parts of this change were drafted with an LLM and reviewed by me.', 'description-statement'],
    ['Used Cursor for the refactoring.', 'description-statement', 'Cursor'],
    ['Copilot suggested most of the regex in this patch.', 'description-statement', 'GitHub Copilot'],
    ['This PR is AI-assisted.', 'description-statement'],
    ['We used ChatGPT to translate the error messages.', 'description-statement', 'ChatGPT'],
    ['AI was used.', 'description-statement'],
    ['Using Claude Code to draft the tests.', 'description-statement', 'Claude'],
    ['AI-assisted.', 'description-statement'],
    ['The tests were generated by Gemini and checked by hand.', 'description-statement', 'Gemini'],
    ['AI-assisted: yes, ChatGPT for the docs', 'description-statement', 'ChatGPT'],
    ['**AI usage:** Claude Code (tests only)', 'description-statement', 'Claude'],
    ['### AI disclosure: Copilot autocomplete', 'description-statement', 'GitHub Copilot'],
    ['Did you use AI? Yes', 'description-statement'],
    ['AI: yes, Copilot completions', 'description-statement', 'GitHub Copilot'],
    ['LLM: Claude Code', 'description-statement', 'Claude'],
    ['Assisted-by: Gemini:gemini-2.5-pro', 'description-trailer', 'Gemini'],
    ['Co-authored-by: Claude <noreply@anthropic.com>', 'description-trailer', 'Claude'],
    ['- [x] I used AI tools for this contribution', 'checkbox'],
    ['* [X] This PR contains AI-generated code (Claude Code)', 'checkbox', 'Claude']
  ]
  for (const [body, kind, tool] of cases) {
    it(`detects: ${body}`, () => {
      const signals = detectInDescription(body)
      expect(signals).toHaveLength(1)
      expect(signals[0]?.kind).toBe(kind)
      expect(signals[0]?.polarity).toBe('positive')
      if (tool) expect(signals[0]?.tool).toBe(tool)
    })
  }
})

describe('description: statements that AI was not used', () => {
  const cases = [
    'No AI was used.',
    'I did not use any AI tools for this change.',
    "I didn't use Copilot or any other AI assistant.",
    'Written without AI assistance.',
    'This PR is not AI-generated.',
    'AI usage: none',
    'AI disclosure: N/A',
    '**AI-assisted:** No',
    'Did you use AI? No',
    '- [x] No AI tools were used in this PR',
    '- [x] This PR does not contain AI-generated code'
  ]
  for (const body of cases) {
    it(`negative: ${body}`, () => {
      const signals = detectInDescription(body)
      expect(signals.map((s) => s.polarity)).toEqual(['negative'])
    })
  }
})

describe('description: false-positive guards', () => {
  const cases = [
    'Fix the MAIN loop in the TRAIN script and update the AIRFLOW config.',
    'Adds an AI-powered summarizer to the dashboard.',
    'Fixes a crash when using Copilot Chat in notebooks.',
    'This PR fixes a crash when using Copilot.',
    'Add support for using an LLM as a judge in evals.',
    'Paginate with a database cursor; used cursor-based pagination for the list endpoint.',
    'Thanks to Devin for the review!',
    'Devin helped me test this on Windows.',
    'Co-authored with Jules from the docs team.',
    'Claude Monet paintings dataset added to the examples.',
    'The LLM generated output is parsed incorrectly; this PR fixes the parser.',
    'Mention AI in the docs index.',
    'This updates the Gemini API client to v2.',
    '- [ ] I used AI tools for this contribution',
    '- [x] I have read the AI contribution policy',
    '- [x] I understand I am responsible for any AI-generated code I submit',
    '<!-- Did you use AI? Describe how, e.g. "I used Claude to write tests" -->',
    '```\nGenerated with Claude Code\n```',
    'Run `copilot --generate` with the new flag.',
    '> I used ChatGPT and it told me to set this flag; that is wrong.',
    'AI usage: <!-- yes/no -->',
    'AI usage: [yes/no]',
    'AI disclosure: see below',
    'Co-authored-by: Jane Doe <jane@example.com>',
    'We use Claude in production for summarization; this PR bumps the SDK.',
    'Using an LLM, the tool now summarizes logs.',
    'AI-generated summaries are now cached for an hour.',
    'Gemini generated responses are now streamed to the client.',
    'Used by the Copilot extension to resolve imports.',
    'AI: the summarizer now batches requests.',
    'This PR was reviewed by Copilot code review before I asked for human review.'
  ]
  for (const body of cases) {
    it(`ignores: ${body.replace(/\n/g, ' ')}`, () => {
      expect(polarity(body)).toEqual([])
    })
  }

  it('ignores a whole unfilled PR template', () => {
    const template = [
      '## Description',
      '<!-- What does this PR do? -->',
      '',
      '## AI disclosure',
      '<!-- If you used AI tools (Copilot, ChatGPT, Claude...), say which and how. -->',
      '- [ ] I used AI tools',
      '- [ ] No AI tools were used',
      '',
      'Fixes #'
    ].join('\n')
    expect(polarity(template)).toEqual([])
  })

  it('reads a filled template', () => {
    const body = [
      '## Description',
      'Adds retries to the uploader.',
      '',
      '## AI disclosure',
      '- [x] I used AI tools',
      '- [ ] No AI tools were used',
      '',
      'I used Claude Code to write the first draft of the retry loop; I rewrote the tests myself.'
    ].join('\n')
    expect(polarity(body)).toEqual(['checkbox:positive', 'description-statement:positive'])
  })
})

describe('commits', () => {
  it('treats Assisted-by and Generated-by trailers as AI trailers', () => {
    const s = detectInCommit(commit('Add retry\n\nAssisted-by: Claude:claude-opus-4-1'), [])
    expect(s).toMatchObject([{ kind: 'commit-trailer', trailerKey: 'assisted-by', tool: 'Claude' }])
    const g = detectInCommit(commit('Add retry\n\nGenerated-by: some-internal-model'), [])
    expect(g).toMatchObject([{ kind: 'commit-trailer', trailerKey: 'generated-by' }])
  })

  it('treats Co-authored-by as AI only for AI identities', () => {
    const cases: [string, string | null][] = [
      ['Co-authored-by: Claude <noreply@anthropic.com>', 'Claude'],
      ['Co-Authored-By: Copilot <175728472+Copilot@users.noreply.github.com>', 'GitHub Copilot'],
      ['co-authored-by: Cursor Agent <cursoragent@cursor.com>', 'Cursor'],
      ['Co-authored-by: aider (anthropic/claude-sonnet-4) <noreply@aider.chat>', 'Aider'],
      ['Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>', 'Devin'],
      ['Co-authored-by: Jane Doe <jane@example.com>', null],
      ['Co-authored-by: Claude Debussy <claude@music.example>', null],
      ['Co-authored-by: Devin Smith <devin@example.com>', null],
      ['Co-authored-by: Jules Verne <jules@example.org>', null],
      ['Co-authored-by: Cody Rhodes <cody@example.org>', null],
      ['Co-authored-by: Sam Altman-Fan <sam@anthropic.com>', null]
    ]
    for (const [trailer, tool] of cases) {
      const s = detectInCommit(commit(`Change\n\n${trailer}`), [])
      expect({ trailer, tool: s[0]?.tool ?? null }).toEqual({ trailer, tool })
    }
  })

  it('detects tool attribution lines and tool identities', () => {
    const msg = 'Add retry\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n'
    expect(detectInCommit(commit(msg), [])).toMatchObject([{ kind: 'commit-attribution', tool: 'Claude' }])
    expect(detectInCommit(commit('Add retry', { authorName: 'Ada (aider)' }), [])).toMatchObject([
      { kind: 'commit-author', tool: 'Aider' }
    ])
    expect(
      detectInCommit(commit('Add retry', { authorLogin: 'copilot-swe-agent[bot]' }), DEFAULT_BOT_AUTHORS)
    ).toMatchObject([{ kind: 'commit-author' }])
  })

  it('does not flag ordinary commits', () => {
    const msg = 'Use the Copilot API for completions\n\nSigned-off-by: Ada Lovelace <ada@example.com>'
    expect(detectInCommit(commit(msg), DEFAULT_BOT_AUTHORS)).toEqual([])
  })
})

describe('detectAiAssistance', () => {
  it('combines description, commits and bot authors', () => {
    const d = detectAiAssistance({
      body: 'No AI was used.',
      authorLogin: 'ada',
      commits: [commit('Fix\n\nAssisted-by: Copilot')],
      botAuthors: DEFAULT_BOT_AUTHORS
    })
    expect(d.aiAssisted).toBe(true)
    expect(d.positive.map((s) => s.kind)).toEqual(['commit-trailer'])
    expect(d.negative.map((s) => s.kind)).toEqual(['description-statement'])
  })

  it('flags configured bot authors, with wildcards', () => {
    const d = detectAiAssistance({ body: '', authorLogin: 'acme-coder[bot]', commits: [], botAuthors: ['*-coder[bot]'] })
    expect(d.positive).toMatchObject([{ kind: 'bot-author', evidence: '@acme-coder[bot]' }])
  })

  it('reports nothing for a plain human PR', () => {
    const d = detectAiAssistance({
      body: 'Fixes #12. Adds a retry to the uploader.',
      authorLogin: 'ada',
      commits: [commit('Add retry')],
      botAuthors: DEFAULT_BOT_AUTHORS
    })
    expect(d).toEqual({ aiAssisted: false, positive: [], negative: [] })
  })
})
